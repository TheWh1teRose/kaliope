"""Per-language resources.

These are *language*-level facts, which §1.3 explicitly permits. Nothing here
describes a publisher, a course or a document layout. A language that is absent
from a table degrades explicitly: the caller either skips the feature or falls
back to a documented default, and says so in the ingestion report.
"""

from __future__ import annotations

from pydantic import BaseModel

#: Sentinel used when the detector cannot commit to a language.
