#: Used when the detected language has no entry. Chosen as the median of the
#: known rates rather than any one language's value.
DEFAULT_WORDS_PER_MINUTE = 150


def resources_for(language: str) -> LanguageResources | None:
    return LANGUAGES.get(language.lower().split("-")[0])


def stopwords_for(language: str) -> frozenset[str]:
    res = resources_for(language)
    return res.stopwords if res else frozenset()


def conjunctions_for(language: str) -> frozenset[str]:
    """Coordinating conjunctions, used by the suspended-compound rule (§5.4.3).

    An unknown language yields the union of every known list. Over-suppressing a
    hyphen join is recoverable — the text keeps a visible hyphen — whereas a
    wrong join fabricates a word that never appeared in the source.
    """
    res = resources_for(language)
    if res is not None:
        return res.coordinating_conjunctions
    union: set[str] = set()
    for lang in LANGUAGES.values():
        union |= lang.coordinating_conjunctions
    return frozenset(union)


def words_per_minute(language: str) -> int:
    res = resources_for(language)
    return res.words_per_minute if res else DEFAULT_WORDS_PER_MINUTE


def supported_languages() -> list[str]:
    return sorted(LANGUAGES)
